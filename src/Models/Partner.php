<?php

declare(strict_types=1);

namespace Hei\ScarlettPlayer\Models;

use Hei\ScarlettPlayer\Exceptions\InvalidPartnerException;
use Hei\ScarlettPlayer\Partners\PartnerParams;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Date;

/**
 * A partner site allowed to frame the embed page.
 *
 * @property int $id
 * @property string $ref
 * @property string $key_id
 * @property string $name
 * @property array<array-key, mixed>|null $origins
 * @property Carbon|null $expires_at
 * @property Carbon|null $revoked_at
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
class Partner extends Model
{
    protected $table = 'scarlett_partners';

    /** key_id is never mass assignable: it is generated, and regenerated by rotate(). */
    protected $guarded = ['id', 'key_id'];

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'origins' => 'array',
            'expires_at' => 'datetime',
            'revoked_at' => 'datetime',
        ];
    }

    protected static function booted(): void
    {
        static::creating(function (self $partner): void {
            if (! PartnerParams::isRef($partner->ref)) {
                throw InvalidPartnerException::invalidRef((string) $partner->ref);
            }

            if (! PartnerParams::isKeyId($partner->key_id ?? null)) {
                $partner->key_id = PartnerParams::newKeyId();
            }
        });

        static::updating(function (self $partner): void {
            if ($partner->isDirty('ref')) {
                throw InvalidPartnerException::refIsImmutable((string) $partner->getOriginal('ref'), (string) $partner->ref);
            }
        });
    }

    /**
     * Generate a new key id, so every snippet minted with the old one stops working. The
     * row is saved.
     */
    public function rotate(): static
    {
        $this->key_id = PartnerParams::newKeyId();
        $this->save();

        return $this;
    }

    /** Whether the partner was revoked: revoked_at is set. A restore clears it. */
    public function isRevoked(): bool
    {
        return $this->revoked_at !== null;
    }

    /** True from the instant of expires_at: a partner expiring at now is already expired. */
    public function isExpired(?Carbon $now = null): bool
    {
        return $this->expires_at !== null && $this->expires_at->lessThanOrEqualTo($now ?? Date::now());
    }

    /** Neither revoked nor expired. */
    public function isActive(?Carbon $now = null): bool
    {
        return ! $this->isRevoked() && ! $this->isExpired($now);
    }
}
